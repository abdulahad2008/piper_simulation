"""Generate the hot-pan variants of the PiPER scene.

    agilex_piper/piper_pan.xml                  piper.xml + a frying pan welded to link6
    agilex_piper/piper_human_pan_task.xml       piper_task.xml (with piper_pan.xml) + stove
                                                + trivet + the human bodies of piper_human_task.xml
    agilex_piper/piper_human_pan_task_torso.xml the same plus a visual-only torso, head and
                                                legs (mocap, moved by the env) for figures

Run `python -m piper_rl.scripts.make_pan_scene` after changing any source file.

Pan: Fissler Cenit 20 cm (top 20 cm, base 14.5 cm, 5.5 cm high, handle 17.5 cm,
525 g; retailer spec, see docs/sharp_tools/PHASE1_AUDIT.md). The frame has +x
from the grip point along the handle toward the pan, +z up (out of the pan),
+y along the finger pinch axis. The grip point is on the `tcp` site, 5 cm from
the handle's free end. With the gripper pointing down the handle is horizontal
and the pan base hangs 5.5 cm below the TCP, so the TCP must stay 6 cm or more
above anything the pan passes over.

Contacts: pan geoms contype=4 conaffinity=3. They touch the person's capsules
(contype 2, conaffinity 3), the table, stove, trivet and object (1/1), and are
excluded pairwise from link6, link7 and link8 so the welded handle does not
fight the finger pads. Robot-link contacts are unchanged.

Named parts: pan_handle (blunt), pan_base and pan_wall_NN (hot surface),
site pan_centre (centre of the base, used for success), site pan_up (base
normal).
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SCENE_DIR = ROOT / "agilex_piper"

TOP_R, BASE_R, HEIGHT = 0.100, 0.0725, 0.055
HANDLE_LEN, HANDLE_HALF_W, HANDLE_HALF_H = 0.175, 0.013, 0.010
GRIP_FROM_END = 0.05
N_WALL = 24
WALL_T = 0.0015
MASS_HANDLE, MASS_BASE, MASS_WALL = 0.10, 0.20, 0.225
CENTRE_X = HANDLE_LEN - GRIP_FROM_END + TOP_R          # 0.225 m from the grip point

# Stove (source) and trivet (target) on the table. pad_src / pad_dst and the
# `target` site of piper_task.xml are kept for the env's bookkeeping; the pan
# task env moves `target` onto the trivet.
STOVE_XY = (0.46, -0.13)
TRIVET_XY = (0.46, 0.15)
TABLE_TOP = 0.20

PAN_ASSETS = """
    <!-- hot pan (generated by piper_rl/scripts/make_pan_scene.py) -->
    <material name="pan_handle" rgba="0.08 0.08 0.08 1"/>
    <material name="pan_steel" rgba="0.26 0.26 0.28 1" specular="0.6" shininess="0.5"/>
    <material name="pan_hot" rgba="0.55 0.12 0.08 1"/>
"""


def _quat_from_matrix(R: np.ndarray) -> np.ndarray:
    """(w, x, y, z) from a rotation matrix."""
    w = np.sqrt(max(0.0, 1 + R[0, 0] + R[1, 1] + R[2, 2])) / 2
    x = np.sqrt(max(0.0, 1 + R[0, 0] - R[1, 1] - R[2, 2])) / 2
    y = np.sqrt(max(0.0, 1 - R[0, 0] + R[1, 1] - R[2, 2])) / 2
    z = np.sqrt(max(0.0, 1 - R[0, 0] - R[1, 1] + R[2, 2])) / 2
    x = np.copysign(x, R[2, 1] - R[1, 2])
    y = np.copysign(y, R[0, 2] - R[2, 0])
    z = np.copysign(z, R[1, 0] - R[0, 1])
    q = np.array([w, x, y, z])
    return q / np.linalg.norm(q)


def pan_body_xml(indent: str = "                  ") -> str:
    """The pan body as a child of link6, positioned at the tcp site."""
    lines = []
    a = lambda s: lines.append(indent + s)
    # link6 frame: z = approach (down when the gripper points down), y = pinch
    # axis, x = handle axis. Rotate 180 deg about y so pan +x = link6 -x
    # (away from the robot base after the IK levels the gripper) and pan +z =
    # link6 -z (up).
    a('<!-- Frying pan held by the handle. Frame: +x grip->pan, +z up, +y pinch axis. -->')
    a('<body name="pan" pos="0 0 0.105" quat="0 0 1 0" gravcomp="1">')
    hx = HANDLE_LEN / 2 - GRIP_FROM_END
    a(f'  <geom name="pan_handle" type="box" size="{HANDLE_LEN/2:.4f} {HANDLE_HALF_W:.4f} {HANDLE_HALF_H:.4f}" '
      f'pos="{hx:.4f} 0 0" material="pan_handle" mass="{MASS_HANDLE}" contype="4" conaffinity="3" group="2"/>')
    base_z = -HEIGHT + WALL_T
    a(f'  <geom name="pan_base" type="cylinder" size="{BASE_R:.4f} {WALL_T:.4f}" '
      f'pos="{CENTRE_X:.4f} 0 {base_z:.4f}" material="pan_hot" mass="{MASS_BASE}" contype="4" conaffinity="3" group="2"/>')
    a(f'  <site name="pan_centre" pos="{CENTRE_X:.4f} 0 {base_z:.4f}" size="0.004" rgba="1 1 0 0.5" group="4"/>')
    a(f'  <site name="pan_up" pos="{CENTRE_X:.4f} 0 {base_z + 0.05:.4f}" size="0.003" rgba="0 1 1 0.5" group="4"/>')
    mean_r = 0.5 * (TOP_R + BASE_R)
    slant = np.hypot(TOP_R - BASE_R, HEIGHT)
    half_tan = np.pi * mean_r / N_WALL * 1.06      # small overlap closes the gaps
    for i in range(N_WALL):
        th = 2 * np.pi * i / N_WALL
        radial = np.array([np.cos(th), np.sin(th), 0.0])
        tang = np.array([-np.sin(th), np.cos(th), 0.0])
        up = np.array([(TOP_R - BASE_R) * np.cos(th), (TOP_R - BASE_R) * np.sin(th), HEIGHT]) / slant
        normal = np.cross(tang, up)
        R = np.stack([normal, tang, up], axis=1)    # local x = normal, y = tangential, z = along the wall
        q = _quat_from_matrix(R)
        c = np.array([CENTRE_X, 0.0, -HEIGHT / 2]) + mean_r * radial
        a(f'  <geom name="pan_wall_{i:02d}" type="box" size="{WALL_T:.4f} {half_tan:.4f} {slant/2:.4f}" '
          f'pos="{c[0]:.4f} {c[1]:.4f} {c[2]:.4f}" quat="{q[0]:.6f} {q[1]:.6f} {q[2]:.6f} {q[3]:.6f}" '
          f'material="pan_steel" mass="{MASS_WALL / N_WALL:.5f}" contype="4" conaffinity="3" group="2"/>')
    a('</body>')
    return "\n".join(lines) + "\n"


EXCLUDES = """
  <contact>
    <!-- the welded pan must not fight the gripper it sits in -->
    <exclude body1="pan" body2="link6"/>
    <exclude body1="pan" body2="link7"/>
    <exclude body1="pan" body2="link8"/>
  </contact>
"""

KITCHEN_FIXTURES = f"""
    <!-- ===== stove and trivet (generated by piper_rl/scripts/make_pan_scene.py) ===== -->
    <!-- Hob plate 30 x 26 cm, 8 mm thick, with a 21 cm ring; trivet 22 cm, 8 mm.
         Both are static collision geoms (contype 1 / conaffinity 1). -->
    <geom name="stove" type="box" size="0.15 0.13 0.004" pos="{STOVE_XY[0]} {STOVE_XY[1]} {TABLE_TOP + 0.004}"
          rgba="0.15 0.15 0.16 1" friction="1.0 0.02 0.001"/>
    <geom name="hob" type="cylinder" size="0.105 0.003" pos="{STOVE_XY[0]} {STOVE_XY[1]} {TABLE_TOP + 0.011}"
          rgba="0.30 0.08 0.05 1" friction="1.0 0.02 0.001"/>
    <geom name="trivet" type="cylinder" size="0.11 0.004" pos="{TRIVET_XY[0]} {TRIVET_XY[1]} {TABLE_TOP + 0.004}"
          rgba="0.72 0.58 0.38 1" friction="1.0 0.02 0.001"/>
    <site name="trivet_centre" pos="{TRIVET_XY[0]} {TRIVET_XY[1]} {TABLE_TOP + 0.008}" size="0.006" rgba="0.3 0.9 0.45 0.6" group="4"/>
    <!-- pulled-back camera showing the whole counter and the floor (figures) -->
    <camera name="counter" pos="1.75 -1.45 0.85" xyaxes="0.7262 0.6875 0 -0.2291 0.2420 0.9428"/>
"""

TORSO = """
    <!-- ===== visual-only torso, head and legs (figures only; moved by the env) ===== -->
    <body name="human_torso" mocap="true" pos="0 0.62 0.54">
      <geom name="human_torso_geom" type="capsule" size="0.14 0.22" pos="-0.17 0 -0.30"
            rgba="0.25 0.40 0.75 1" contype="0" conaffinity="0" group="2"/>
      <geom name="human_head_geom" type="sphere" size="0.10" pos="-0.17 0 0.20"
            rgba="0.85 0.62 0.48 1" contype="0" conaffinity="0" group="2"/>
      <geom name="human_leg_l_geom" type="capsule" size="0.07 0.32" pos="-0.08 0 -0.90"
            rgba="0.30 0.32 0.40 1" contype="0" conaffinity="0" group="2"/>
      <geom name="human_leg_r_geom" type="capsule" size="0.07 0.32" pos="-0.26 0 -0.90"
            rgba="0.30 0.32 0.40 1" contype="0" conaffinity="0" group="2"/>
    </body>
"""


def build_piper_pan(src: str) -> str:
    out = src.replace('<mujoco model="piper_description">', '<mujoco model="piper_description_pan">', 1)
    out = out.replace("<asset>", "<asset>" + PAN_ASSETS, 1)
    marker = '                  <body name="link7"'
    assert out.count(marker) == 1, "link7 marker not found exactly once in piper.xml"
    out = out.replace(marker, pan_body_xml() + marker, 1)
    assert out.count("</mujoco>") == 1
    return out.replace("</mujoco>", EXCLUDES.lstrip("\n") + "</mujoco>", 1)


def build_human_pan_task(task_src: str, human_src: str, torso: bool) -> str:
    name = "piper_human_aware_pan_task" + ("_torso" if torso else "")
    out = task_src.replace('<mujoco model="piper_pick_place">', f'<mujoco model="{name}">', 1)
    assert '<include file="piper.xml"/>' in out
    out = out.replace('<include file="piper.xml"/>', '<include file="piper_pan.xml"/>', 1)
    # the cup's source/destination pads and target marker play no part here: keep
    # the named geoms and site for the env's bookkeeping, draw nothing
    out = out.replace('material="src" contype="0"', 'rgba="0 0 0 0" contype="0"', 1)
    out = out.replace('material="dst" contype="0"', 'rgba="0 0 0 0" contype="0"', 1)
    out = out.replace('rgba="0.3 0.9 0.45 0.9"/>', 'rgba="0.3 0.9 0.45 0"/>', 1)
    material = re.search(r"<asset>\s*(<material name=\"human_skin\"[^>]*/>)\s*</asset>", human_src)
    bodies = re.search(r"<worldbody>(.*)</worldbody>", human_src, re.S)
    assert material and bodies, "unexpected piper_human_task.xml layout"
    out = out.replace("  <worldbody>", "  <asset>\n    " + material.group(1) + "\n  </asset>\n\n  <worldbody>", 1)
    # The person is kinematic and never reacts, so a contact with the welded
    # pan must be DETECTED but carry NO FORCE: an infinite-mass mocap capsule
    # pushing a tool welded to the arm flings the robot (seen in the first
    # preview). gap="1" keeps every person contact in data.contact and out of
    # the solver (active only below margin - gap = -1 m, i.e. never).
    human_bodies = bodies.group(1).replace('contype="2" conaffinity="3"', 'contype="2" conaffinity="3" gap="1"')
    assert human_bodies.count('gap="1"') == 3
    extra = KITCHEN_FIXTURES + "\n    <!-- ===== human arm (from piper_human_task.xml); contacts detected, force-free (gap) ===== -->" + human_bodies.rstrip()
    if torso:
        extra += "\n" + TORSO.rstrip()
    out = out.replace("  </worldbody>", extra + "\n  </worldbody>", 1)
    return out


def generate() -> dict[str, str]:
    piper = (SCENE_DIR / "piper.xml").read_text()
    task = (SCENE_DIR / "piper_task.xml").read_text()
    human = (SCENE_DIR / "piper_human_task.xml").read_text()
    return {
        "piper_pan.xml": build_piper_pan(piper),
        "piper_human_pan_task.xml": build_human_pan_task(task, human, torso=False),
        "piper_human_pan_task_torso.xml": build_human_pan_task(task, human, torso=True),
    }


def main() -> None:
    for name, text in generate().items():
        (SCENE_DIR / name).write_text(text)
        print("wrote", SCENE_DIR / name)


if __name__ == "__main__":
    main()
